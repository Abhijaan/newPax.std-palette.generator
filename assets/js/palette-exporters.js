/**
 * Platform export serializers.
 *
 * Each function accepts palette data and returns file contents. Keep DOM reads,
 * downloads, and UI notifications in the application controller instead.
 */
import { hexToRgb } from './palette-engine.js';

/** Build the versioned JSON representation of a generated palette. */
export function paletteObject(current, seedHex) {
  return {
    schemaVersion: '1.0.0',
    algorithmVersion: '0.1.0',
    mode: current.mode,
    seed: seedHex,
    hsb: {
      h: Number(current.hsb.h.toFixed(4)),
      s: Number(current.hsb.s.toFixed(4)),
      b: Number(current.hsb.b.toFixed(4))
    },
    fallbackReason: current.mode === 'fallback' ? current.reason : null,
    colors: Object.fromEntries(current.colors.map(color => [color.name, color.hex]))
  };
}

/** Serialize palette shades as Android `colors.xml` resources. */
export function xmlExport(current) {
  const colors = current.colors
    .map(color => `    <color name="${color.name.toLowerCase()}">${color.hex}</color>`)
    .join('\n');

  return `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n${colors}\n</resources>\n`;
}

/**
 * Fixed Jetpack Compose export template.
 *
 * This deliberately emits a constructor-based BrandColorPalette instance rather
 * than an object of standalone shade properties. Keep this template code-defined
 * so generated files remain consistent and require no persisted user settings.
 */
export function kotlinExport(current) {
  const declarations = current.colors
    .map((color, index) => {
      const shade = color.name.replace('BrandPrimary', '');
      const separator = index < current.colors.length - 1 ? ',' : '';
      const coreComment = shade === '600' ? ' // Core brand colour' : '';
      return `    brandPrimary${shade} = Color(0xFF${color.hex.slice(1)})${separator}${coreComment}`;
    })
    .join('\n');

  return [
    'private val BRAND_COLOR_PALETTE = BrandColorPalette(',
    declarations,
    ')',
    ''
  ].join('\n');
}

/** Serialize valid Swift property names for use with SwiftUI. */
export function swiftExport(current) {
  const declarations = current.colors
    .map(color => {
      const shade = color.name.replace('BrandPrimary', '');
      const { r, g, b } = hexToRgb(color.hex);
      const red = (r / 255).toFixed(6);
      const green = (g / 255).toFixed(6);
      const blue = (b / 255).toFixed(6);

      return `    static let shade${shade} = Color(red: ${red}, green: ${green}, blue: ${blue})`;
    })
    .join('\n');

  return [
    'import SwiftUI',
    'import UIKit',
    '',
    '// Generated by Color Palette Studio. Review before committing.',
    'enum BrandPrimary {',
    declarations,
    '}',
    ''
  ].join('\n');
}

/** Create the `Contents.json` payload for one Xcode color asset. */
export function assetContents(hex) {
  const { r, g, b } = hexToRgb(hex);
  const toComponent = value => (value / 255).toFixed(6);

  return `${JSON.stringify({
    colors: [{
      color: {
        colorSpace: 'srgb',
        components: {
          alpha: '1.000',
          red: toComponent(r),
          green: toComponent(g),
          blue: toComponent(b)
        }
      }
    }],
    info: { author: 'xcode', version: 1 }
  }, null, 2)}\n`;
}
