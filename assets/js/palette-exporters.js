/**
 * Color Palette Studio — export serializers
 * Converts a generated palette into platform-specific file contents.
 */
import { hexToRgb } from "./palette-engine.js";

export function paletteObject(current, seedHex) {
  return {
    schemaVersion: "1.0.0",
    algorithmVersion: "0.1.0",
    mode: current.mode,
    seed: seedHex,
    hsb: {
      h: Number(current.hsb.h.toFixed(4)),
      s: Number(current.hsb.s.toFixed(4)),
      b: Number(current.hsb.b.toFixed(4))
    },
    fallbackReason: current.mode === "fallback" ? current.reason : null,
    colors: Object.fromEntries(current.colors.map(color => [color.name, color.hex]))
  };
}

export function xmlExport(current) {
  return `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n${current.colors.map(color => `    <color name="${color.name.toLowerCase()}">${color.hex}</color>`).join("\n")}\n</resources>\n`;
}

export function kotlinExport(current) {
  return `package com.example.designsystem.colors\n\nimport androidx.compose.ui.graphics.Color\n\n// Generated by Color Palette Studio. Review before committing.\nobject BrandPrimary {\n${current.colors.map(color => `    val ${color.name.replace("BrandPrimary", "")} = Color(0xFF${color.hex.slice(1)})`).join("\n")}\n}\n`;
}

export function swiftExport(current) {
  return `import SwiftUI\nimport UIKit\n\n// Generated by Color Palette Studio. Review before committing.\nenum BrandPrimary {\n${current.colors.map(color => {
    const rgb = hexToRgb(color.hex);
    return `    static let ${color.name.replace("BrandPrimary", "")} = Color(red: ${(rgb.r / 255).toFixed(6)}, green: ${(rgb.g / 255).toFixed(6)}, blue: ${(rgb.b / 255).toFixed(6)})`;
  }).join("\n")}\n}\n`;
}

export function assetContents(hex) {
  const { r, g, b } = hexToRgb(hex);
  const rgba = value => (value / 255).toFixed(6);
  return JSON.stringify({
    colors: [{ color: { colorSpace: "srgb", components: {
      alpha: "1.000", red: rgba(r), green: rgba(g), blue: rgba(b)
    } } }],
    info: { author: "xcode", version: 1 }
  }, null, 2) + "\n";
}
